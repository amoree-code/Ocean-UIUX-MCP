// Regenerates everything derived from styles/ and components/previews/:
//   1. patches known upstream example bugs in every style (idempotent)
//   2. copies each preview into styles/<style>/previews/ with style-local imports
//   3. writes lib/style-loaders.ts (lazy import map: style → slug → module)
// Run after editing a preview: `pnpm gen:styles`.
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const stylesDir = path.join(root, "styles")
const previewsDir = path.join(root, "components/previews")

const styles = fs
  .readdirSync(stylesDir)
  .filter((s) => fs.existsSync(path.join(stylesDir, s, "ui")))
  .sort((a, b) => (a === "nova" ? -1 : b === "nova" ? 1 : a.localeCompare(b)))

const patches = [
  // Base UI prop values leak into the Radix context-menu example.
  ["context-menu-example.tsx", [[/side="inline-end"/g, 'side="right"'], [/side="inline-start"/g, 'side="left"']]],
  // The chart example reads the shadcn site's own search-params hook.
  [
    "chart-example.tsx",
    [
      [/^import \{ useDesignSystemSearchParams \}.*\n/m, ""],
      [/^\s*const \[params\] = useDesignSystemSearchParams\(\)\n/m, ""],
      [/const isRounded = .*$/m, "const isRounded = true"],
    ],
  ],
]

function moduleExpr(file, spec) {
  const src = fs.readFileSync(file, "utf8")
  if (/export default/.test(src)) return `import("${spec}")`
  const named = src.match(/export function (\w+)/)
  if (!named) throw new Error(`${file}: no default or named function export`)
  return `import("${spec}").then((m) => ({ default: m.${named[1]} }))`
}

const previews = fs.existsSync(previewsDir)
  ? fs.readdirSync(previewsDir).filter((f) => f.endsWith(".tsx"))
  : []

const lines = [
  "// GENERATED by scripts/gen-style-loaders.mjs — do not edit.",
  'import type { ComponentType } from "react"',
  "",
  "type Loader = () => Promise<{ default: ComponentType }>",
  "",
  `export const styles = ${JSON.stringify(styles)} as const`,
  "export type Style = (typeof styles)[number]",
  "",
]
const examples = {}
const previewMap = {}

for (const style of styles) {
  const dir = path.join(stylesDir, style)

  for (const [file, rules] of patches) {
    const p = path.join(dir, file)
    if (!fs.existsSync(p)) continue
    let src = fs.readFileSync(p, "utf8")
    for (const [from, to] of rules) src = src.replace(from, to)
    fs.writeFileSync(p, src)
  }

  fs.rmSync(path.join(dir, "previews"), { recursive: true, force: true })
  fs.mkdirSync(path.join(dir, "previews"))
  for (const f of previews) {
    // Only official ui is vendored per style; community ui stays in components/ui.
    const src = fs
      .readFileSync(path.join(previewsDir, f), "utf8")
      .replace(/@\/components\/ui\/([\w-]+)/g, (m, name) =>
        fs.existsSync(path.join(dir, "ui", `${name}.tsx`)) ? `@/styles/${style}/ui/${name}` : m
      )
    fs.writeFileSync(path.join(dir, "previews", f), src)
  }

  examples[style] = []
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".tsx") && f !== "example.tsx").sort()) {
    const base = f.replace(/\.tsx$/, "")
    const slug = base.replace(/-example$/, "")
    examples[style].push(`    "${slug}": () => ${moduleExpr(path.join(dir, f), `@/styles/${style}/${base}`)},`)
  }
  previewMap[style] = previews.map((f) => {
    const slug = f.replace(/\.tsx$/, "")
    return `    "${slug}": () => ${moduleExpr(path.join(dir, "previews", f), `@/styles/${style}/previews/${slug}`)},`
  })
}

const block = (name, map) => [
  `export const ${name}: Record<Style, Record<string, Loader>> = {`,
  ...styles.flatMap((s) => [`  ${s}: {`, ...map[s], "  },"]),
  "}",
  "",
]
lines.push(...block("exampleLoaders", examples), ...block("previewLoaders", previewMap))
fs.writeFileSync(path.join(root, "lib/style-loaders.ts"), lines.join("\n"))
console.log(`styles: ${styles.join(", ")} · previews: ${previews.length}`)
